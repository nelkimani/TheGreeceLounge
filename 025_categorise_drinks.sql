insert into categories(name)
select distinct c.cat from _cat_map c
where not exists (select 1 from categories x where lower(x.name) = lower(c.cat));

do $$
declare r record; n int := 0;
begin
  for r in
    select p.id, p.name, p.category_id as old_id, (select x.id from categories x where lower(x.name) = lower(m.cat) limit 1) as new_id, m.cat
    from products p join _cat_map m on m.k = regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g')
    where p.category_id is distinct from (select x.id from categories x where lower(x.name) = lower(m.cat) limit 1)
  loop
    update products set category_id = r.new_id where id = r.id;
    perform write_audit('product.category', 'products', r.id::text,
      jsonb_build_object('category_id', r.old_id), jsonb_build_object('category_id', r.new_id), 'Category set to ' || r.cat || ' (migration 025)');
    n := n + 1;
  end loop;
  raise notice '% drink(s) moved to their category', n;
end $$;

commit;
